/**
 * What `build` writes, without writing it: every target in tokens.config.json, rendered. `build` writes these,
 * `check` compares them with the files on disk, `doctor` names the stale ones.
 */
import { dirname, join } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

import { loadTokens } from './resolve.mjs';

const here = dirname(fileURLToPath(import.meta.url));

/** The resolved tokens, with what every target reads besides them: the app root and the generated-file header. */
export async function loadContext(root, source) {
  const ctx = await loadTokens(join(root, source));
  ctx.root = root;
  ctx.header = `GENERATED by \`npm run tokens:build\` from ${source} — do not edit by hand.`;
  return ctx;
}

/** [{ path, contents }] for every target in the config, relative to the app root. */
export async function renderTargets(ctx, config) {
  const files = [];
  for (const [name, options] of Object.entries(config.targets ?? {})) {
    const { default: target } = await import(pathToFileURL(join(here, '..', 'targets', `${name}.mjs`)).href);
    files.push(...(await target(ctx, options ?? {})));
  }
  return files;
}
